function validateSource() {
  const errors = [];
  const libraryIds = new Set();
  const entryIds = new Set();
  for (const [language] of languageContracts) {
    const count = libraries.filter((library) => library.language === language).length;
    if (count !== 3) errors.push(`${language} has ${count} libraries instead of 3.`);
  }

  if (libraries.length !== 30) {
    errors.push(`Expected 30 libraries, received ${libraries.length}.`);
  }

  for (const library of libraries) {
    if (!languageContracts.has(library.language)) {
      errors.push(`${library.id} uses unsupported language '${library.language}'.`);
    }
    if (libraryIds.has(library.id)) errors.push(`Duplicate library ID '${library.id}'.`);
    libraryIds.add(library.id);
    if (library.recipes.length !== 3) {
      errors.push(`${library.id} has ${library.recipes.length} recipes instead of 3.`);
    }
    for (const item of library.recipes) {
      const entryId = `${library.id}.${item.id}`;
      if (entryIds.has(entryId)) errors.push(`Duplicate entry ID '${entryId}'.`);
      entryIds.add(entryId);
      for (const itemParameter of item.parameters) {
        const placeholder = `{${itemParameter.placeholder}}`;
        if (!item.template.includes(placeholder)) {
          errors.push(`${entryId} declares unused placeholder '${placeholder}'.`);
        }
      }
      for (const itemParameter of item.parameters) {
        const placeholder = `{${itemParameter.placeholder}}`;
        if (item.exampleCode.includes(placeholder)) {
          errors.push(`${entryId} example contains unresolved placeholder '${placeholder}'.`);
        }
      }
    }
  }

  if (errors.length > 0) {
    throw new Error(`Popular library starter source is invalid:\n- ${errors.join("\n- ")}`);
  }
}

function json(value, compact = false) {
  return `${JSON.stringify(value, null, compact ? 0 : 2)}\n`;
}

function unique(values) {
  return [...new Set(values)];
}

