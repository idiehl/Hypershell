using System.Net;
using System.Text;
using Hypershell.Models;

namespace Hypershell.Services;

public sealed class VisualPageGeneratedArtifact
{
    public required string RelativePath { get; init; }
    public required string Content { get; init; }
    public string Sha256 => VisualPageHashing.Sha256Text(Content);
}

public sealed class VisualPageGenerationResult
{
    public required IReadOnlyList<VisualPageGeneratedArtifact> Artifacts { get; init; }
    public required IReadOnlyList<VisualPageSourceMapping> SourceMappings { get; init; }
    public required IReadOnlyList<VisualPageCodeClassification> Classifications { get; init; }
}

public sealed class VisualPageGenerator
{
    private static readonly IReadOnlyDictionary<VisualPageBreakpoint, int>
        BreakpointWidths = new Dictionary<VisualPageBreakpoint, int>
        {
            [VisualPageBreakpoint.Small] = 576,
            [VisualPageBreakpoint.Medium] = 768,
            [VisualPageBreakpoint.Large] = 992,
            [VisualPageBreakpoint.ExtraLarge] = 1200
        };
    private readonly VisualPageComponentCatalog _catalog;
    private readonly VisualPageSchemaValidator _validator;

    public VisualPageGenerator(
        VisualPageComponentCatalog catalog,
        VisualPageSchemaValidator validator)
    {
        _catalog = catalog;
        _validator = validator;
    }

    public VisualPageGenerationResult Generate(
        VisualPageProjectManifest project,
        VisualPageDocument page)
    {
        ArgumentNullException.ThrowIfNull(project);
        ArgumentNullException.ThrowIfNull(page);
        _validator.ThrowIfInvalid(page);
        return VisualPageProjectService.ResolvePageFileType(project, page) switch
        {
            HyperpagePageFileType.Html => GenerateHtml(project, page),
            HyperpagePageFileType.Cshtml => GenerateCshtml(project, page),
            _ => GenerateRazorPage(project, page)
        };
    }

    private VisualPageGenerationResult GenerateRazorPage(
        VisualPageProjectManifest project,
        VisualPageDocument page)
    {
        var mappings = new List<VisualPageSourceMapping>();
        var razor = new LineWriter();
        razor.Write("@* <auto-generated by Hypershell Hyperpage Studio; edit the Hyperpage document, not this file> *@");
        razor.Write($"@namespace {project.RootNamespace}.Generated");
        razor.Write($"@page \"{EscapeRazorString(page.Route)}\"");
        razor.Write(string.Empty);
        razor.Write(
            $"<link rel=\"stylesheet\" href=\"_content/{project.RootNamespace}/visual-page-theme.css\" />");
        WriteSharedStylesheetLinks(razor, project, 0);
        razor.Write(
            $"<link rel=\"stylesheet\" href=\"_content/{project.RootNamespace}/{page.ComponentName}.custom.css\" />");
        WriteStylesheetLinks(razor, project, page, 0);
        WriteElement(razor, page.Root, mappings, depth: 0);

        var css = GenerateCss(page);
        var designer = GenerateDesigner(project, page);
        var basePath = $"src/Pages/Generated/{page.ComponentName}";
        var artifacts = new List<VisualPageGeneratedArtifact>
        {
            Artifact($"{basePath}.razor", razor.ToString()),
            Artifact($"{basePath}.razor.css", css),
            Artifact($"{basePath}.designer.g.cs", designer),
            Artifact("src/Pages/wwwroot/visual-page-theme.css", GenerateThemeCss(project))
        };
        var classifications = CollectClassifications(page);
        return new VisualPageGenerationResult
        {
            Artifacts = artifacts,
            SourceMappings = mappings,
            Classifications = classifications
                .Distinct()
                .OrderBy(value => value)
            .ToList()
        };
    }

    private VisualPageGenerationResult GenerateHtml(
        VisualPageProjectManifest project,
        VisualPageDocument page)
    {
        EnsureHtmlCompatible(page);
        var mappings = new List<VisualPageSourceMapping>();
        var html = new LineWriter();
        html.Write("<!doctype html>");
        html.Write("<html lang=\"en\">");
        html.Write(1, "<head>");
        html.Write(2, "<meta charset=\"utf-8\" />");
        html.Write(2, "<meta name=\"viewport\" content=\"width=device-width, initial-scale=1\" />");
        html.Write(2, $"<title>{WebUtility.HtmlEncode(page.Title)}</title>");
        if (!string.IsNullOrWhiteSpace(page.Description))
        {
            html.Write(
                2,
                $"<meta name=\"description\" content=\"{WebUtility.HtmlEncode(page.Description)}\" />");
        }
        html.Write(2, "<link rel=\"stylesheet\" href=\"/app.css\" />");
        html.Write(2, "<link rel=\"stylesheet\" href=\"/assets/hyperpage-theme.css\" />");
        WriteSharedStylesheetLinks(html, project, 2);
        html.Write(2, $"<link rel=\"stylesheet\" href=\"/assets/{page.Slug}.generated.css\" />");
        html.Write(2, $"<link rel=\"stylesheet\" href=\"/assets/{page.Slug}.custom.css\" />");
        WriteStylesheetLinks(html, project, page, 2);
        html.Write(1, "</head>");
        html.Write(1, "<body>");
        WriteHtmlElement(html, page.Root, mappings, depth: 2);
        WriteSharedScripts(html, project, 2);
        html.Write(2, $"<script src=\"/assets/{page.Slug}.custom.js\" defer></script>");
        html.Write(1, "</body>");
        html.Write("</html>");

        var artifacts = new List<VisualPageGeneratedArtifact>
        {
            Artifact(
                VisualPageProjectService.GeneratedMarkupPath(project, page),
                html.ToString()),
            Artifact(
                $"src/Host/wwwroot/assets/{page.Slug}.generated.css",
                GenerateCss(page)),
            Artifact(
                "src/Host/wwwroot/assets/hyperpage-theme.css",
                GenerateThemeCss(project))
        };
        return new VisualPageGenerationResult
        {
            Artifacts = artifacts,
            SourceMappings = mappings,
            Classifications = CollectClassifications(page)
                .Distinct()
                .OrderBy(value => value)
                .ToList()
        };
    }

    private VisualPageGenerationResult GenerateCshtml(
        VisualPageProjectManifest project,
        VisualPageDocument page)
    {
        EnsureHtmlCompatible(page);
        var mappings = new List<VisualPageSourceMapping>();
        var markup = new LineWriter();
        markup.Write($"@page \"{EscapeRazorString(page.Route)}\"");
        markup.Write("@{ Layout = null; }");
        markup.Write("<!doctype html>");
        markup.Write("<html lang=\"en\">");
        markup.Write(1, "<head>");
        markup.Write(2, "<meta charset=\"utf-8\" />");
        markup.Write(2, "<meta name=\"viewport\" content=\"width=device-width, initial-scale=1\" />");
        markup.Write(2, $"<title>{WebUtility.HtmlEncode(page.Title)}</title>");
        if (!string.IsNullOrWhiteSpace(page.Description))
        {
            markup.Write(
                2,
                $"<meta name=\"description\" content=\"{WebUtility.HtmlEncode(page.Description)}\" />");
        }
        markup.Write(2, "<link rel=\"stylesheet\" href=\"/app.css\" />");
        markup.Write(2, "<link rel=\"stylesheet\" href=\"/assets/hyperpage-theme.css\" />");
        WriteSharedStylesheetLinks(markup, project, 2);
        markup.Write(2, $"<link rel=\"stylesheet\" href=\"/assets/{page.Slug}.generated.css\" />");
        markup.Write(2, $"<link rel=\"stylesheet\" href=\"/assets/{page.Slug}.custom.css\" />");
        WriteStylesheetLinks(markup, project, page, 2);
        markup.Write(1, "</head>");
        markup.Write(1, "<body>");
        WriteHtmlElement(markup, page.Root, mappings, depth: 2);
        WriteSharedScripts(markup, project, 2);
        markup.Write(2, $"<script src=\"/assets/{page.Slug}.custom.js\" defer></script>");
        markup.Write(1, "</body>");
        markup.Write("</html>");

        return new VisualPageGenerationResult
        {
            Artifacts =
            [
                Artifact(
                    VisualPageProjectService.GeneratedMarkupPath(project, page),
                    markup.ToString()),
                Artifact(
                    $"src/Host/wwwroot/assets/{page.Slug}.generated.css",
                    GenerateCss(page)),
                Artifact(
                    "src/Host/wwwroot/assets/hyperpage-theme.css",
                    GenerateThemeCss(project))
            ],
            SourceMappings = mappings,
            Classifications = CollectClassifications(page)
                .Distinct()
                .OrderBy(value => value)
                .ToList()
        };
    }

    private static void WriteStylesheetLinks(
        LineWriter writer,
        VisualPageProjectManifest project,
        VisualPageDocument page,
        int depth)
    {
        foreach (var path in page.StylesheetPaths.Distinct(StringComparer.OrdinalIgnoreCase))
        {
            var url = WebUtility.HtmlEncode(HyperpageStylesheetService.PublishedUrl(project, path));
            writer.Write(depth, $"<link rel=\"stylesheet\" href=\"{url}\" />");
        }
    }

    private static void WriteSharedStylesheetLinks(LineWriter writer, VisualPageProjectManifest project, int depth)
    {
        foreach (var path in (project.SharedStylesheetPaths ?? []).Distinct(StringComparer.OrdinalIgnoreCase))
        {
            var url = WebUtility.HtmlEncode(HyperpageStylesheetService.PublishedUrl(project, path));
            writer.Write(depth, $"<link rel=\"stylesheet\" href=\"{url}\" />");
        }
    }

    internal static string SharedScriptUrl(string relativePath)
    {
        const string prefix = "src/Host/wwwroot/";
        var path = (relativePath ?? "").Replace('\\', '/');
        if (!path.StartsWith(prefix, StringComparison.OrdinalIgnoreCase)
            || !path.EndsWith(".js", StringComparison.OrdinalIgnoreCase)
            || path.Split('/').Any(part => string.IsNullOrWhiteSpace(part) || part is "." or ".."
                || part.IndexOfAny(System.IO.Path.GetInvalidFileNameChars()) >= 0))
            throw new VisualPageValidationException("Shared browser scripts must be .js files inside src/Host/wwwroot.");
        return "/" + string.Join('/', path[prefix.Length..].Split('/').Select(Uri.EscapeDataString));
    }

    private static void WriteSharedScripts(LineWriter writer, VisualPageProjectManifest project, int depth)
    {
        foreach (var path in (project.SharedJavaScriptPaths ?? []).Distinct(StringComparer.OrdinalIgnoreCase))
            writer.Write(depth, $"<script src=\"{WebUtility.HtmlEncode(SharedScriptUrl(path))}\" defer></script>");
    }

    private void EnsureHtmlCompatible(VisualPageDocument page)
    {
        if (!string.Equals(
                page.Route,
                VisualPageProjectService.NormalizeHtmlRoute(
                    page.Route,
                    page.Slug),
                StringComparison.Ordinal))
        {
            throw new VisualPageValidationException(
                "Static HTML routes must use plain path segments such as /about or /products/details.");
        }
        var unsupported = Flatten(page.Root).FirstOrDefault(element =>
            element.Bindings.Count > 0
            || element.Events.Count > 0
            || element.DescriptorId is "core.condition" or "core.loop" or "custom.razor"
            || element.IsCustomCode
            || _catalog.GetRequired(element.DescriptorId).MarkupName.Any(char.IsUpper));
        if (page.State.Count > 0 || unsupported is not null)
        {
            throw new VisualPageValidationException(
                "This HTML project contains Razor, C#, binding, event, or component logic. Choose Razor Pages for those features, or remove the dynamic element before generating static HTML.");
        }
    }

    private void WriteHtmlElement(
        LineWriter writer,
        VisualPageElement element,
        List<VisualPageSourceMapping> mappings,
        int depth)
    {
        var descriptor = _catalog.GetRequired(element.DescriptorId);
        var startLine = writer.LineNumber + 1;
        if (element.IsHidden)
        {
            writer.Write(depth, $"<!-- Hidden Hyperpage element {element.ElementId} -->");
            mappings.Add(Map(element, startLine, writer.LineNumber));
            return;
        }

        var attributes = BuildHtmlAttributes(element, descriptor);
        var opening = attributes.Count == 0
            ? $"<{descriptor.MarkupName}"
            : $"<{descriptor.MarkupName} {string.Join(" ", attributes)}";
        if (descriptor.IsVoid)
        {
            writer.Write(depth, opening + " />");
            mappings.Add(Map(element, startLine, writer.LineNumber));
            return;
        }

        writer.Write(depth, opening + ">");
        if (!string.IsNullOrEmpty(element.Text))
        {
            writer.Write(depth + 1, WebUtility.HtmlEncode(element.Text));
        }
        foreach (var child in element.Children)
        {
            WriteHtmlElement(writer, child, mappings, depth + 1);
        }
        writer.Write(depth, $"</{descriptor.MarkupName}>");
        mappings.Add(Map(element, startLine, writer.LineNumber));
    }

    private List<string> BuildHtmlAttributes(
        VisualPageElement element,
        VisualPageComponentDescriptor descriptor)
    {
        var attributes = new SortedDictionary<string, string>(
            element.Attributes,
            StringComparer.Ordinal);
        var cssClass = $"vp-{ShortId(element.ElementId)}";
        if (attributes.TryGetValue("class", out var existingClass)
            && !string.IsNullOrWhiteSpace(existingClass))
        {
            cssClass += " " + existingClass.Trim();
        }
        attributes["class"] = cssClass;
        attributes["data-vp-id"] = element.ElementId;

        var output = new List<string>();
        foreach (var pair in attributes)
        {
            if (_catalog.TryGetAttributeDefinition(
                    descriptor,
                    pair.Key,
                    out var definition)
                && definition.EditorKind == VisualPageAttributeEditorKind.Boolean)
            {
                if (!pair.Value.Equals("false", StringComparison.OrdinalIgnoreCase))
                {
                    output.Add(pair.Key);
                }
                continue;
            }
            output.Add($"{pair.Key}=\"{WebUtility.HtmlEncode(pair.Value)}\"");
        }
        return output;
    }

    internal static string GenerateThemeCss(VisualPageProjectManifest project)
    {
        var names = new Dictionary<string, string>(StringComparer.Ordinal)
        {
            ["color.background"] = "background",
            ["color.surface"] = "surface",
            ["color.text"] = "text",
            ["color.muted"] = "muted",
            ["color.accent"] = "accent",
            ["radius.card"] = "radius-card",
            ["space.section"] = "space-section"
        };
        var css = new StringBuilder();
        css.AppendLine(":root {");
        foreach (var token in project.Theme.Tokens.OrderBy(value => value.Key, StringComparer.Ordinal))
        {
            var name = names.GetValueOrDefault(
                token.Key,
                token.Key.Replace('.', '-').ToLowerInvariant());
            css.Append("  --vp-")
                .Append(name)
                .Append(": ")
                .Append(token.Value.Trim())
                .AppendLine(";");
        }
        css.AppendLine("}");
        return css.ToString();
    }

    private void WriteElement(
        LineWriter writer,
        VisualPageElement element,
        List<VisualPageSourceMapping> mappings,
        int depth)
    {
        var descriptor = _catalog.GetRequired(element.DescriptorId);
        var startLine = writer.LineNumber + 1;
        if (element.IsHidden)
        {
            writer.Write(depth, $"@* Hidden visual element {element.ElementId} *@");
            mappings.Add(Map(element, startLine, writer.LineNumber));
            return;
        }

        var visibility = element.Bindings.FirstOrDefault(binding =>
            binding.Kind == VisualPageBindingKind.Visibility);
        if (visibility is not null)
        {
            writer.Write(depth, $"@if ({visibility.Expression})");
            writer.Write(depth, "{");
            depth++;
        }

        if (element.DescriptorId == "core.condition")
        {
            var expression = GetRequiredStructuralExpression(
                element,
                "condition",
                "Condition");
            writer.Write(depth, $"@if ({expression})");
            writer.Write(depth, "{");
            foreach (var child in element.Children)
            {
                WriteElement(writer, child, mappings, depth + 1);
            }
            writer.Write(depth, "}");
        }
        else if (element.DescriptorId == "core.loop")
        {
            var expression = GetRequiredStructuralExpression(
                element,
                "items",
                "Items");
            var itemName = element.Attributes.GetValueOrDefault("item", "item");
            writer.Write(depth, $"@foreach (var {itemName} in {expression})");
            writer.Write(depth, "{");
            foreach (var child in element.Children)
            {
                WriteElement(writer, child, mappings, depth + 1);
            }
            writer.Write(depth, "}");
        }
        else if (element.DescriptorId == "custom.razor")
        {
            writer.Write(depth, $"@* Hyperpage custom fragment {element.ElementId}; reviewed-code lane *@");
            foreach (var line in NormalizeLines(element.CustomRazor ?? string.Empty))
            {
                writer.Write(depth, line);
            }
            writer.Write(depth, $"@* End custom fragment {element.ElementId} *@");
        }
        else
        {
            WriteMarkupElement(writer, element, descriptor, mappings, depth);
        }

        if (visibility is not null)
        {
            depth--;
            writer.Write(depth, "}");
        }

        mappings.Add(Map(element, startLine, writer.LineNumber));
    }

    private void WriteMarkupElement(
        LineWriter writer,
        VisualPageElement element,
        VisualPageComponentDescriptor descriptor,
        List<VisualPageSourceMapping> mappings,
        int depth)
    {
        var attributes = BuildAttributes(element, descriptor);
        var opening = attributes.Count == 0
            ? $"<{descriptor.MarkupName}"
            : $"<{descriptor.MarkupName} {string.Join(" ", attributes)}";
        if (descriptor.IsVoid)
        {
            writer.Write(depth, opening + " />");
            return;
        }

        var text = ResolveText(element);
        if (element.Children.Count == 0 && string.IsNullOrEmpty(text))
        {
            writer.Write(depth, opening + $"></{descriptor.MarkupName}>");
            return;
        }

        writer.Write(depth, opening + ">");
        if (!string.IsNullOrEmpty(text))
        {
            writer.Write(depth + 1, text);
        }

        foreach (var child in element.Children)
        {
            WriteElement(writer, child, mappings, depth + 1);
        }

        writer.Write(depth, $"</{descriptor.MarkupName}>");
    }

    private List<string> BuildAttributes(
        VisualPageElement element,
        VisualPageComponentDescriptor descriptor)
    {
        var attributes = new SortedDictionary<string, string>(
            element.Attributes,
            StringComparer.Ordinal);
        var cssClass = $"vp-{ShortId(element.ElementId)}";
        if (attributes.TryGetValue("class", out var existingClass)
            && !string.IsNullOrWhiteSpace(existingClass))
        {
            cssClass += " " + existingClass.Trim();
        }

        attributes["class"] = cssClass;
        if (descriptor.MarkupName.All(character => char.IsLower(character)))
        {
            attributes["data-vp-id"] = element.ElementId;
        }

        var output = new List<string>();
        foreach (var pair in attributes)
        {
            if (_catalog.TryGetAttributeDefinition(
                    descriptor,
                    pair.Key,
                    out var definition)
                && definition.EditorKind ==
                VisualPageAttributeEditorKind.Boolean)
            {
                if (pair.Value.Equals("false", StringComparison.OrdinalIgnoreCase))
                {
                    continue;
                }
                output.Add(pair.Key);
                continue;
            }
            output.Add($"{pair.Key}=\"{WebUtility.HtmlEncode(pair.Value)}\"");
        }
        foreach (var binding in element.Bindings
                     .Where(binding => binding.Kind is
                         VisualPageBindingKind.Attribute
                         or VisualPageBindingKind.Value
                         or VisualPageBindingKind.CssClass)
                     .OrderBy(binding => binding.Target, StringComparer.Ordinal))
        {
            var attributeName = binding.Kind switch
            {
                VisualPageBindingKind.Value when descriptor.MarkupName
                    .StartsWith("Input", StringComparison.Ordinal) => "@bind-Value",
                VisualPageBindingKind.Value => "@bind",
                VisualPageBindingKind.CssClass => "class",
                _ => binding.Target
            };
            output.RemoveAll(value =>
                value.Equals(attributeName, StringComparison.Ordinal)
                || value.StartsWith(
                    attributeName + "=",
                    StringComparison.Ordinal));
            output.Add($"{attributeName}=\"@({binding.Expression})\"");
        }

        foreach (var eventBinding in element.Events
                     .OrderBy(value => value.Kind))
        {
            output.Add($"{EventAttribute(eventBinding.Kind)}=\"{eventBinding.HandlerName}\"");
        }

        return output;
    }

    private static string ResolveText(VisualPageElement element)
    {
        var binding = element.Bindings.FirstOrDefault(value =>
            value.Kind == VisualPageBindingKind.Text);
        if (binding is not null)
        {
            return string.IsNullOrWhiteSpace(binding.Format)
                ? $"@({binding.Expression})"
                : $"@(string.Format(\"{EscapeRazorString(binding.Format)}\", {binding.Expression}))";
        }

        return WebUtility.HtmlEncode(element.Text);
    }

    private static string GenerateCss(VisualPageDocument page)
    {
        var writer = new LineWriter();
        writer.Write("/* <auto-generated by Hypershell Hyperpage Studio> */");
        foreach (var element in Flatten(page.Root))
        {
            WriteCssRule(writer, element, VisualPageBreakpoint.Base, media: false);
        }

        foreach (var breakpoint in BreakpointWidths.Keys)
        {
            var responsive = Flatten(page.Root)
                .Where(element => element.Layout.ContainsKey(breakpoint))
                .ToList();
            if (responsive.Count == 0)
            {
                continue;
            }

            writer.Write(string.Empty);
            writer.Write($"@media (min-width: {BreakpointWidths[breakpoint]}px) {{");
            foreach (var element in responsive)
            {
                WriteCssRule(writer, element, breakpoint, media: true);
            }
            writer.Write("}");
        }

        return writer.ToString();
    }

    private static void WriteCssRule(
        LineWriter writer,
        VisualPageElement element,
        VisualPageBreakpoint breakpoint,
        bool media)
    {
        element.Layout.TryGetValue(breakpoint, out var layout);
        if (layout is null
            && (breakpoint != VisualPageBreakpoint.Base
                || element.Styles.Count == 0))
        {
            return;
        }

        var indent = media ? 1 : 0;
        writer.Write(indent, $".vp-{ShortId(element.ElementId)} {{");
        if (breakpoint == VisualPageBreakpoint.Base)
        {
            foreach (var style in element.Styles.OrderBy(
                         pair => pair.Key,
                         StringComparer.Ordinal))
            {
                writer.Write(indent + 1, $"{style.Key}: {style.Value};");
            }
        }
        if (layout is not null)
        {
            foreach (var declaration in LayoutDeclarations(layout))
            {
                writer.Write(indent + 1, declaration);
            }
        }
        writer.Write(indent, "}");
    }

    private static IEnumerable<string> LayoutDeclarations(
        VisualPageLayoutSpec layout)
    {
        if (!string.IsNullOrWhiteSpace(layout.Display))
            yield return $"display: {layout.Display};";
        if (!string.IsNullOrWhiteSpace(layout.FlexDirection))
            yield return $"flex-direction: {layout.FlexDirection};";
        if (!string.IsNullOrWhiteSpace(layout.FlexWrap))
            yield return $"flex-wrap: {layout.FlexWrap};";
        if (!string.IsNullOrWhiteSpace(layout.GridTemplateColumns))
            yield return $"grid-template-columns: {layout.GridTemplateColumns};";
        if (layout.ColumnSpan is { } columnSpan)
            yield return $"grid-column: span {columnSpan};";
        if (layout.RowSpan is { } rowSpan)
            yield return $"grid-row: span {rowSpan};";
        if (!string.IsNullOrWhiteSpace(layout.FlexBasis))
            yield return $"flex-basis: {layout.FlexBasis};";
        if (!string.IsNullOrWhiteSpace(layout.Gap))
            yield return $"gap: {layout.Gap};";
        if (!string.IsNullOrWhiteSpace(layout.Padding))
            yield return $"padding: {layout.Padding};";
        if (!string.IsNullOrWhiteSpace(layout.Margin))
            yield return $"margin: {layout.Margin};";
        if (!string.IsNullOrWhiteSpace(layout.MinWidth))
            yield return $"min-width: {layout.MinWidth};";
        if (!string.IsNullOrWhiteSpace(layout.MaxWidth))
            yield return $"max-width: {layout.MaxWidth};";
        if (!string.IsNullOrWhiteSpace(layout.MinHeight))
            yield return $"min-height: {layout.MinHeight};";
        if (!string.IsNullOrWhiteSpace(layout.MaxHeight))
            yield return $"max-height: {layout.MaxHeight};";
        if (!string.IsNullOrWhiteSpace(layout.AlignItems))
            yield return $"align-items: {layout.AlignItems};";
        if (!string.IsNullOrWhiteSpace(layout.JustifyContent))
            yield return $"justify-content: {layout.JustifyContent};";
        if (!string.IsNullOrWhiteSpace(layout.AlignSelf))
            yield return $"align-self: {layout.AlignSelf};";
    }

    private static string GenerateDesigner(
        VisualPageProjectManifest project,
        VisualPageDocument page)
    {
        var writer = new LineWriter();
        writer.Write("// <auto-generated by Hypershell Hyperpage Studio />");
        writer.Write("using Microsoft.AspNetCore.Components;");
        writer.Write("using Microsoft.AspNetCore.Components.Web;");
        writer.Write(string.Empty);
        writer.Write($"namespace {project.RootNamespace}.Generated;");
        writer.Write(string.Empty);
        writer.Write($"public partial class {page.ComponentName}");
        writer.Write("{");
        foreach (var state in page.State.OrderBy(
                     state => state.Name,
                     StringComparer.Ordinal))
        {
            if (state.Kind == VisualPageStateKind.Parameter)
            {
                writer.Write(1, "[Parameter]");
                if (state.IsRequired)
                {
                    writer.Write(1, "[EditorRequired]");
                }
                writer.Write(1, $"public {state.TypeName} {state.Name} {{ get; set; }} = {state.InitialValue};");
            }
            else
            {
                writer.Write(1, $"protected {state.TypeName} {state.Name} {{ get; set; }} = {state.InitialValue};");
            }
            writer.Write(string.Empty);
        }

        foreach (var eventBinding in Flatten(page.Root)
                     .SelectMany(element => element.Events)
                     .GroupBy(binding => binding.HandlerName, StringComparer.Ordinal)
                     .Select(group => group.First())
                     .OrderBy(binding => binding.HandlerName, StringComparer.Ordinal))
        {
            var argumentType = ResolveEventArgumentType(eventBinding);
            if (string.IsNullOrEmpty(argumentType))
            {
                writer.Write(1, $"private void {eventBinding.HandlerName}() => {eventBinding.HandlerName}Core();");
                writer.Write(1, $"partial void {eventBinding.HandlerName}Core();");
            }
            else
            {
                writer.Write(1, $"private void {eventBinding.HandlerName}({argumentType} args) => {eventBinding.HandlerName}Core(args);");
                writer.Write(1, $"partial void {eventBinding.HandlerName}Core({argumentType} args);");
            }
            writer.Write(string.Empty);
        }
        writer.Write("}");
        return writer.ToString();
    }

    private static string ResolveEventArgumentType(
        VisualPageEventBinding eventBinding)
    {
        if (!string.IsNullOrWhiteSpace(eventBinding.ArgumentType))
        {
            return eventBinding.ArgumentType;
        }

        return eventBinding.Kind switch
        {
            VisualPageEventKind.Click => "MouseEventArgs",
            VisualPageEventKind.Change or VisualPageEventKind.Input =>
                "ChangeEventArgs",
            VisualPageEventKind.Focus or VisualPageEventKind.Blur =>
                "FocusEventArgs",
            VisualPageEventKind.KeyDown => "KeyboardEventArgs",
            _ => string.Empty
        };
    }

    private static string EventAttribute(VisualPageEventKind kind) => kind switch
    {
        VisualPageEventKind.Click => "@onclick",
        VisualPageEventKind.Change => "@onchange",
        VisualPageEventKind.Input => "@oninput",
        VisualPageEventKind.Submit => "@onsubmit",
        VisualPageEventKind.Focus => "@onfocus",
        VisualPageEventKind.Blur => "@onblur",
        VisualPageEventKind.KeyDown => "@onkeydown",
        _ => throw new ArgumentOutOfRangeException(nameof(kind))
    };

    private static string GetRequiredStructuralExpression(
        VisualPageElement element,
        string attributeName,
        string fallback)
    {
        var expression = element.Attributes.GetValueOrDefault(
            attributeName,
            fallback);
        if (string.IsNullOrWhiteSpace(expression))
        {
            throw new VisualPageValidationException(
                $"{element.Name} requires a {attributeName} expression.");
        }

        return expression;
    }

    private HashSet<VisualPageCodeClassification>
        CollectClassifications(VisualPageDocument page)
    {
        var values = new HashSet<VisualPageCodeClassification>
        {
            VisualPageCodeClassification.Declarative
        };
        if (page.State.Count > 0)
        {
            values.Add(VisualPageCodeClassification.CustomCSharp);
        }
        foreach (var element in Flatten(page.Root))
        {
            var descriptor = _catalog.GetRequired(element.DescriptorId);
            values.Add(descriptor.Classification);
            if (element.DescriptorId == "custom.razor")
            {
                values.Add(VisualPageCodeClassification.CustomRazor);
            }
            else if (element.DescriptorId == "custom.component")
            {
                values.Add(VisualPageCodeClassification.CustomComponent);
            }
            if (element.Bindings.Count > 0
                || element.DescriptorId is "core.condition" or "core.loop"
                || element.Events.Any(eventBinding =>
                    !string.IsNullOrWhiteSpace(eventBinding.ArgumentType)))
            {
                values.Add(VisualPageCodeClassification.CustomCSharp);
            }
        }
        return values;
    }

    private static IEnumerable<VisualPageElement> Flatten(
        VisualPageElement root)
    {
        yield return root;
        foreach (var child in root.Children)
        {
            foreach (var descendant in Flatten(child))
            {
                yield return descendant;
            }
        }
    }

    private static VisualPageSourceMapping Map(
        VisualPageElement element,
        int start,
        int end) => new()
        {
            ElementId = element.ElementId,
            StartLine = start,
            EndLine = Math.Max(start, end)
        };

    private static VisualPageGeneratedArtifact Artifact(
        string path,
        string content) => new()
        {
            RelativePath = path,
            Content = content.Replace("\r\n", "\n", StringComparison.Ordinal)
        };

    private static string ShortId(string elementId) =>
        elementId.Length <= 12 ? elementId : elementId[..12];

    private static string EscapeRazorString(string value) =>
        value.Replace("\\", "\\\\", StringComparison.Ordinal)
            .Replace("\"", "\\\"", StringComparison.Ordinal);

    private static IEnumerable<string> NormalizeLines(string value) =>
        value.Replace("\r\n", "\n", StringComparison.Ordinal)
            .Replace('\r', '\n')
            .Split('\n');

    private sealed class LineWriter
    {
        private readonly StringBuilder _builder = new();

        public int LineNumber { get; private set; }

        public void Write(string value) => Write(0, value);

        public void Write(int depth, string value)
        {
            if (depth > 0 && value.Length > 0)
            {
                _builder.Append(' ', depth * 4);
            }
            _builder.Append(value);
            _builder.Append('\n');
            LineNumber++;
        }

        public override string ToString() => _builder.ToString();
    }
