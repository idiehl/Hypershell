import assert from 'node:assert/strict';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { chromium, expect } from '@playwright/test';

const origin = 'http://127.0.0.1:5292', qa = 'output/right-panel-qa';
const filename = path.join(process.env.LOCALAPPDATA, 'AtlasMeridian/projects/e35cba82-f644-416a-ac14-12645893ed88/project.json');
const source = await readFile(filename), digest = bytes => createHash('sha256').update(bytes).digest('hex');
const savedDocument = JSON.parse(source.toString('utf8')), project = savedDocument.project ?? savedDocument;
const sourceRevision = project.revision;
const nodeId = '005fe68a-bc30-4b11-af1d-4dadec799b1c', node = project.nodes.find(node => node.id === nodeId);
assert.equal(node?.kind, 'image'); assert.equal(project.nodes.find(parent => parent.id === node.parentId)?.kind, 'canvas');
project.id = crypto.randomUUID(); project.revision = 0;
const response = await fetch(`${origin}/api/projects`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(project) });
assert.ok(response.ok, `Isolated fixture creation failed: ${response.status}`);
const savedBefore = await (await fetch(`${origin}/api/projects/${project.id}`)).text();
await mkdir(qa, { recursive: true });
const browser = await chromium.launch();
const context = await browser.newContext({ viewport: { width: 1700, height: 1080 } });
const page = await context.newPage(), errors = [];
page.on('pageerror', error => errors.push(error.message));
try {
  await page.goto(`${origin}/?project=${project.id}&canvas=${node.canvasId}`);
  await expect(page.locator('.sidebar,.canvas-list')).toHaveCount(0);
  await page.getByRole('searchbox', { name: 'Find a node' }).fill(nodeId);
  await page.locator(`button[data-navigation-node="${nodeId}"]`).click();
  await page.getByRole('searchbox', { name: 'Find a node' }).fill('');
  const tile = page.locator(`.ms-node[data-node-id="${nodeId}"]`);
  await expect(tile.locator('img')).toBeVisible();
  await expect(tile.getByRole('button', { name: /^Open / })).toHaveCount(0);
  await expect(page.locator('.inspector-properties input').first()).toHaveValue(node.title);
  await page.screenshot({ path: `${qa}/visual-atlas-zeus-canvas.png` });
  const opening = page.waitForEvent('popup');
  await tile.locator('img').click({ modifiers: ['Control'] });
  const media = await opening;
  await expect(media.getByRole('main', { name: 'Image viewer' })).toBeVisible();
  await expect(media.locator('.media-window-stage img')).toHaveJSProperty('complete', true);
  assert.ok(await media.locator('.media-window-stage img').evaluate(image => image.naturalWidth > 0));
  await media.screenshot({ path: `${qa}/visual-atlas-zeus-image-window.png` });
  await media.close();
  assert.equal(await tile.getAttribute('aria-selected'), 'true');
  const parentId = '9ca61bc8-e4a3-4743-b4da-437668cc288e';
  await page.getByRole('searchbox', { name: 'Find a node' }).fill(parentId);
  await page.locator(`button[data-navigation-node="${parentId}"]`).click();
  await page.getByRole('searchbox', { name: 'Find a node' }).fill('');
  await page.locator('.inspector-properties .containment-heading').first().scrollIntoViewIfNeeded();
  await expect(page.locator('.child-canvas-open')).toHaveCount(4);
  await page.screenshot({ path: `${qa}/visual-atlas-parent-canvases.png` });
  assert.equal(await (await fetch(`${origin}/api/projects/${project.id}`)).text(), savedBefore, 'Review changed its isolated fixture');
  assert.equal(digest(await readFile(filename)), digest(source), 'Review changed the original project file');
  assert.deepEqual(errors, []);
  await writeFile(`${qa}/visual-atlas-review.json`, JSON.stringify({ origin, sourceRevision, nodeId, nodeTitle: node.title, noSidebar: true, imageButtonRemoved: true, imageWindow: true, childCanvasActions: 4, savedFixtureUnchanged: true, sourceFileUnchanged: true, browserErrors: errors }, null, 2));
  console.log('Reviewed the actual Zeus image and four parent-contained canvas launchers on an isolated copy; source and fixture unchanged.');
} finally { await context.close(); await browser.close(); }
