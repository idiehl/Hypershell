import assert from 'node:assert/strict';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { chromium, firefox } from '@playwright/test';

const root=fileURLToPath(new URL('../../',import.meta.url));
const directory=path.join(root,'examples/visual-authoring');
const qa=path.join(directory,'qa-expanded');await mkdir(qa,{recursive:true});
const project=JSON.parse(await readFile(path.join(directory,'visual-atlas.project.json'),'utf8'));
const aliases=JSON.parse(await readFile(path.join(directory,'visual-atlas.aliases.json'),'utf8'));
const engine=process.argv.includes('--firefox')?'firefox':'chromium';
const browser=await (engine==='firefox'?firefox:chromium).launch({headless:true});
const page=await browser.newPage({viewport:{width:1600,height:1100},acceptDownloads:true,offline:true});
page.setDefaultTimeout(15000);
const errors=[],requests=[],checks=[];
page.on('pageerror',e=>errors.push(e.message));
page.on('request',r=>{if(/^https?:/.test(r.url()))requests.push(r.url());});
const node=key=>page.locator(`.ms-node[data-node-id="${aliases.nodes[key]}"]`);
const choose=async key=>{await page.getByLabel('Choose canvas',{exact:true}).selectOption(aliases.canvases[key]);await page.getByRole('button',{name:'Fit canvas',exact:true}).click();};
const screenshot=async name=>page.screenshot({path:path.join(qa,`${engine}-${name}.png`)});
try {
  await page.goto(pathToFileURL(path.join(directory,'visual-atlas.html')).href,{timeout:90000});
  const authored=await page.locator('#meridian-data').textContent();
  assert.equal(await page.locator('.mv-status').textContent(),'Stopped');
  await choose('iliad-24');
  const book=project.nodes.find(n=>n.id===aliases.nodes['iliad-24-source']);
  const asset=project.assets.find(a=>a.id===book.assetId),full=Buffer.from(asset.base64,'base64').toString('utf8');
  await node('iliad-24-source').getByRole('button',{name:`Open ${asset.name}`,exact:true}).click();
  assert.equal(await page.locator('.ms-dialog-text').textContent(),full);assert.ok(full.length>20000);
  await screenshot('complete-book');
  await page.getByRole('button',{name:'Close attachment',exact:true}).click();
  checks.push('The entire Iliad Book24 translation opens offline, including text beyond the preview.');
  const query=full.slice(8000).match(/[A-Za-z][A-Za-z ,']{55,75}/)[0].trim();
  await choose('family');
  await page.getByRole('button',{name:'Explore project',exact:true}).click();
  await page.getByRole('searchbox',{name:'Search project'}).fill(query);
  await page.locator(`.mv-search-result[data-navigation-node="${book.id}"]`).click();
  assert.equal(await page.getByLabel('Choose canvas',{exact:true}).inputValue(),book.canvasId);
  await page.getByRole('button',{name:'Close project navigation',exact:true}).click();
  await page.getByRole('button',{name:'Fit canvas',exact:true}).click();
  await node('iliad-24-lens').getByRole('button',{name:'Expand Interpretive lens',exact:true}).click();
  assert.equal(await node('iliad-24-themes').count(),1);
  await node('iliad-24-lens').getByRole('button',{name:'Collapse Interpretive lens',exact:true}).click();
  assert.equal(await node('iliad-24-themes').count(),0);
  assert.match(await node('iliad-24-lens').innerText(),/reading aids/);
  checks.push('Cross-canvas search finds full attachment text; collapse keeps the summary and hides only the child.');
  await choose('media-lab');
  await page.getByRole('button',{name:'Run simulation',exact:true}).click();
  assert.match(await node('lab-output').innerText(),/On/);
  await node('lab-logic').getByRole('button',{name:'Collapse A reading comparison',exact:true}).click();
  assert.equal(await node('lab-input-one').count(),0);assert.equal(await node('lab-output').count(),1);
  assert.match(await node('lab-output').innerText(),/On/);
  await page.getByRole('button',{name:'Fit canvas',exact:true}).click();await screenshot('collapsed-logic');
  await node('lab-logic').getByRole('button',{name:'Expand A reading comparison',exact:true}).click();
  await node('lab-switch').getByRole('switch',{name:'Connection: toggle switch',exact:true}).click();
  assert.match(await node('lab-output').innerText(),/Unknown/);
  await page.getByRole('button',{name:'Stop simulation',exact:true}).click();
  await choose('family');assert.equal(await page.locator('.mv-status').textContent(),'Stopped');
  await choose('media-lab');assert.match(await node('lab-switch').innerText(),/Open/);
  await page.getByRole('button',{name:'Run simulation',exact:true}).click();
  assert.match(await node('lab-output').innerText(),/Unknown/);
  checks.push('Hidden logic continues computing; sibling output stays present, open switch clears dependents, and Stop persists across canvases.');
  await choose('zeus-index');
  await node('zeus-original').click();
  await page.getByRole('button',{name:'Explore project',exact:true}).click();
  await page.getByRole('searchbox',{name:'Search project'}).fill('');
  await page.getByRole('button',{name:'Open original context',exact:true}).click();
  assert.equal(await page.getByLabel('Choose canvas',{exact:true}).inputValue(),aliases.canvases.family);
  await page.getByRole('button',{name:'Back',exact:true}).click();
  assert.equal(await page.getByLabel('Choose canvas',{exact:true}).inputValue(),aliases.canvases['zeus-index']);
  await page.getByRole('button',{name:'Forward',exact:true}).click();
  assert.equal(await page.getByLabel('Choose canvas',{exact:true}).inputValue(),aliases.canvases.family);
  checks.push('Saved-reference original context, backlinks and viewer history navigate real atlas data.');
  await page.setViewportSize({width:390,height:820});await screenshot('mobile-search');
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  await page.getByRole('button',{name:'Close project navigation',exact:true}).click();
  const downloaded=page.waitForEvent('download');
  await page.getByRole('button',{name:'Download this published canvas for viewing or importing into the Meridian editor',exact:true}).click();
  const copy=await downloaded,html=await readFile(await copy.path(),'utf8');
  const savedPayload=html.match(/<script[^>]*id="meridian-data"[^>]*>([\s\S]*?)<\/script>/)[1];
  assert.deepEqual(JSON.parse(savedPayload),JSON.parse(authored));
  assert.equal(await page.locator('#meridian-data').textContent(),authored);
  checks.push('A 390px viewer has no page overflow; downloaded HTML retains authored defaults despite runtime interactions.');
  const iframePath=path.join(qa,`embed-${engine}.html`);
  await writeFile(iframePath,'<!doctype html><html><head><meta name="viewport" content="width=device-width,initial-scale=1"><title>Meridian embed verification</title></head><body style="margin:0"><iframe title="Greek mythology" src="../visual-atlas.html" style="display:block;border:0;width:100%;height:100vh"></iframe></body></html>');
  await page.goto(pathToFileURL(iframePath).href,{timeout:90000});
  const iframe=page.frameLocator('iframe');
  await iframe.getByRole('button',{name:'Explore project',exact:true}).click();
  await iframe.getByRole('searchbox',{name:'Search project'}).fill('Athena');
  assert.ok(await iframe.locator('.mv-search-result').count()>0);await screenshot('mobile-iframe');
  await page.setViewportSize({width:1600,height:1100});await screenshot('desktop-iframe');
  checks.push('The same file works inside a desktop and 390px iframe with networking disabled.');
  assert.deepEqual(requests,[]);assert.deepEqual(errors,[]);
  const report={engine,canvases:project.canvases.length,nodes:project.nodes.length,checks,requests,errors};
  await writeFile(path.join(qa,`${engine}-browser-report.json`),JSON.stringify(report,null,2));console.log(JSON.stringify(report,null,2));
} finally { await browser.close(); }
