export const FONT_FAMILIES = [
  { value: 'sans', label: 'Sans serif', css: 'Inter, "Segoe UI", system-ui, sans-serif', category: 'sans-serif', monospace: false },
  { value: 'serif', label: 'Serif', css: 'Georgia, "Times New Roman", serif', category: 'serif', monospace: false },
  { value: 'mono', label: 'Monospace', css: 'Consolas, "Courier New", monospace', category: 'monospace', monospace: true },
  ...NAMED_FONTS.map(([value, label, category]) => ({ value, label, category, css: `"${label}", ${FALLBACKS[category]}`, monospace: category === 'monospace' })),
] as const;
export type FontFamily = typeof FONT_FAMILIES[number]['value'];
export type FontDefinition = typeof FONT_FAMILIES[number];
const fontIds = new Set<string>(FONT_FAMILIES.map(font => font.value));
const definitions = new Map<string, FontDefinition>(FONT_FAMILIES.map(font => [font.value, font]));
export const isFontFamily = (value: unknown): value is FontFamily => typeof value === 'string' && fontIds.has(value);
/** Omitted or unsupported document values retain the original sans-serif default. */
export const fontFamily = (value?: string): FontDefinition => definitions.get(value ?? 'sans') ?? FONT_FAMILIES[0];

