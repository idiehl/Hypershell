import { test, expect } from '@playwright/test';
import { addNode, commitSnapshots, newProject } from '../src/core/model.ts';
import { reflowContainedChildren } from '../src/core/grid.ts';

test('Window links follow scrolled tiles, clip labels in world coordinates, and hide offscreen endpoints', async ({ page, request }) => {
  let project = newProject('Window link clipping QA');
  const parent = addNode(project, project.entryCanvasId, 'container', 'Window links');
  Object.assign(parent, { x: 100, y: 100, containerVariant: 'window', collapsed: false });
  parent.grid = { columns: 2, rows: 4, cellWidth: 160, cellHeight: 100, windowColumns: 2, windowRows: 2, scrollDirection: 'vertical' };
  const a = addNode(project, project.entryCanvasId, 'text', 'Linked object A');
  const b = addNode(project, project.entryCanvasId, 'text', 'Linked object B');
  Object.assign(a, { parentId: parent.id, cell: { column: 1, row: 2 } });
  Object.assign(b, { parentId: parent.id, cell: { column: 2, row: 2 } });
  const linkId = crypto.randomUUID();
  project.links.push({ id: linkId, canvasId: parent.canvasId, parentId: parent.id, sourceId: a.id, targetId: b.id, kind: 'visual', relation: 'generic', label: 'Shared window relation' });
  project = reflowContainedChildren(project, parent.id);
  const placedA=project.nodes.find(node=>node.id===a.id)!,placedB=project.nodes.find(node=>node.id===b.id)!;
  Object.assign(project.links[0],{sourceAnchor:{x:.5,y:0},targetAnchor:{x:.5,y:0},points:[{x:(placedA.x+placedB.x+160)/2,y:placedA.y-20}]});
  const response = await request.post('/api/projects', { data: commitSnapshots(project) });
  expect(response.ok(), await response.text()).toBeTruthy();
  await page.goto(`/?project=${project.id}`);
  const pane = page.locator(`.ms-window-viewport[data-window-id="${parent.id}"]`);
  const line = page.locator(`.ms-link[data-link-id="${linkId}"] .ms-link-line`);
  const label = page.locator(`.ms-link-label-group[data-link-id="${linkId}"]`);
  await expect(pane).toBeVisible(); await expect(line).toBeVisible();
  const before = await line.getAttribute('d');
  const clip = await label.evaluate(element => ({ own: element.getAttribute('clip-path'), parent: element.parentElement!.getAttribute('clip-path') }));
  expect(clip.own).toBeNull(); expect(clip.parent).toMatch(/^url\(#.+\)$/);
  await pane.evaluate(element => { element.scrollTop = 100; });
  await expect.poll(() => pane.evaluate(element => element.scrollTop)).toBe(100);
  await expect.poll(() => line.getAttribute('d')).not.toBe(before);
  await expect(line).toBeVisible();
  await pane.evaluate(element => { element.scrollTop = 200; });
  await expect(line).toBeHidden(); await expect(label).toBeHidden();
  await pane.click({position:{x:100,y:150}});
  await expect(page.locator(`.ms-node[data-node-id="${parent.id}"]`)).toHaveClass(/ms-selected/);
  await page.getByRole('button',{name:'New Node',exact:true}).click();await page.getByRole('menuitem',{name:'Node',exact:true}).click();
  await pane.click({position:{x:100,y:150}});
  const dialog=page.getByRole('dialog',{name:'New Node',exact:true});await expect(dialog).toContainText(`Create a child of ${parent.title}`);
  await dialog.getByLabel('Behavior',{exact:true}).selectOption('sticky');await expect(dialog.getByLabel('Parent edge',{exact:true})).toBeHidden();
  await page.keyboard.press('Escape');
  const saved = await (await request.get(`/api/projects/${project.id}`)).json();
  expect(saved.revision).toBe(1); expect(saved.nodes.find((node: { id: string }) => node.id === a.id).cell).toEqual(a.cell);
});

test('Nested Window route clips intersect the outer viewport after scrolling', async ({ page, request }) => {
  let project=newProject('Nested Window clipping QA');
  const outer=addNode(project,project.entryCanvasId,'container','Outer window');
  Object.assign(outer,{x:100,y:100,containerVariant:'window',collapsed:false});
  outer.grid={columns:1,rows:2,cellWidth:400,cellHeight:320,windowColumns:1,windowRows:1,scrollDirection:'vertical'};
  const inner=addNode(project,project.entryCanvasId,'container','Inner window');
  Object.assign(inner,{parentId:outer.id,containerVariant:'window',collapsed:false,cell:{column:1,row:1}});
  inner.grid={columns:2,rows:3,cellWidth:160,cellHeight:100,windowColumns:2,windowRows:2,scrollDirection:'vertical'};
  const a=addNode(project,project.entryCanvasId,'text','Inner linked A'),b=addNode(project,project.entryCanvasId,'text','Inner linked B');
  Object.assign(a,{parentId:inner.id,cell:{column:1,row:2}});Object.assign(b,{parentId:inner.id,cell:{column:2,row:2}});
  project=reflowContainedChildren(project,inner.id);project=reflowContainedChildren(project,outer.id);
  const pa=project.nodes.find(node=>node.id===a.id)!,pb=project.nodes.find(node=>node.id===b.id)!,linkId=crypto.randomUUID();
  project.links.push({id:linkId,canvasId:outer.canvasId,parentId:inner.id,sourceId:a.id,targetId:b.id,kind:'visual',relation:'generic',label:'Nested clipped relation',sourceAnchor:{x:.5,y:0},targetAnchor:{x:.5,y:0},points:[{x:(pa.x+pb.x+160)/2,y:pa.y-100}]});
  const response=await request.post('/api/projects',{data:commitSnapshots(project)});expect(response.ok(),await response.text()).toBeTruthy();
  await page.goto(`/?project=${project.id}`);
  const pane=page.locator(`.ms-window-viewport[data-window-id="${outer.id}"]`),line=page.locator(`.ms-link[data-link-id="${linkId}"]`);
  const clipId=(await line.getAttribute('clip-path'))!.slice(5,-1),clip=page.locator(`clipPath[id="${clipId}"] rect`);
  await expect(clip).toHaveAttribute('height','200');
  const initialY=Number(await clip.getAttribute('y'));
  await pane.evaluate(element=>{element.scrollTop=100;});
  await expect.poll(async()=>Number(await clip.getAttribute('height'))).toBeLessThan(200);
  expect(Number(await clip.getAttribute('y'))).toBeGreaterThan(initialY-100);
  await expect(line).toBeVisible();
});
